/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_TIM1_Init();
  /* USER CODE BEGIN 2 */
  WS2812_Init();

  uint8_t b_pulses = 0, btn_prev = 1;
  uint8_t r_brightness = 0, g_brightness = 0, b_brightness = 0;
  uint32_t r_tick = 0, g_tick = 0, b_tick = 0, btn_tick = 0;
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
	/*
	 * Button handling
	 * To minimize external components needed we are using
	 * an internal pullup and software debouncing
	 * */
	if(!HAL_GPIO_ReadPin(BTN_GPIO, BTN_PIN) & (btn_prev == 1) &
		((HAL_GetTick() - btn_tick) >= BTN_DEBOUNCE)) {
	  btn_tick = HAL_GetTick();
	  btn_prev = 0;

	  b_pulses = 3;
	  b_tick = 0;
	} else if(HAL_GPIO_ReadPin(BTN_GPIO, BTN_PIN) &
	  	((HAL_GetTick() - btn_tick) >= BTN_DEBOUNCE)) {
	  btn_tick = HAL_GetTick();
	  btn_prev = 1;
	}

	/*
	 * Red - 50% duty cycle square wave
	 * */
	if(HAL_GetTick() - r_tick >= 1500) {
	  r_tick = HAL_GetTick();

	  r_brightness = r_brightness==0 ? 255 : 0;
	}

	/*
	 * Green - sawtooth
	 * 3000ms period / 256 values is roughly 11.7ms per step
	 * We need to round it to 12, so resulting period would be 3072ms
	 * We can get closer to 3s if we count only to 249 ((249+1)*12ms=3000ms)
	 * */
	if(HAL_GetTick() - g_tick >= 12) {
	  g_tick = HAL_GetTick();

	  g_brightness++;

	  if(g_brightness >= 250) {
		g_brightness = 0;
	  }
	}

	/*
	 * Blue - 3 pulses after clicking a button
	 * */
	if((b_pulses > 0) & (HAL_GetTick() - b_tick >= 500)) {
	  b_tick = HAL_GetTick();

	  if(b_brightness == 0) {
	  	b_brightness = 255;
	  } else {
	  	b_brightness = 0;
	  	b_pulses--;
	  }
	}

	WS2812_SetLED(0, r_brightness, g_brightness, b_brightness);
	WS2812_Update();
  }
  /* USER CODE END 3 */
}

